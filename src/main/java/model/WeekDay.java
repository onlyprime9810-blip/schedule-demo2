package model;

/**
 * Представляет дни недели, в которые могут проводиться учебные занятия.
 * Воскресенье не включено, так как оно обычно является выходным днем.
 */
public enum WeekDay {

    /** Понедельник */
    MONDAY,

    /** Вторник */
    TUESDAY,

    /** Среда */
    WEDNESDAY,

    /** Четверг */
    THURSDAY,

    /** Пятница */
    FRIDAY,

    /** Суббота */
    SATURDAY
}