package model;

/**
 * Представляет четность учебной недели (используется для составления расписания на семестр).
 * Позволяет задать, проводится ли занятие каждую неделю, только по четным или только по нечетным.
 */
public enum WeekParity {

    /** Занятие проводится каждую неделю */
    EVERY,

    /** Занятие проводится только по четным неделям */
    EVEN,

    /** Занятие проводится только по нечетным неделям */
    ODD;

    /**
     * Проверяет, подходит ли указанная неделя под данную четность.
     *
     * @param weekNumber номер недели от начала семестра (нумерация начинается с 1)
     * @return true, если занятие должно проводиться на этой неделе, иначе false
     */
    public boolean matches(int weekNumber) {
        return switch (this) {
            case EVERY -> true;
            case EVEN -> weekNumber % 2 == 0;
            case ODD -> weekNumber % 2 == 1;
        };
    }
}