package model;

import java.util.List;

/**
 * Представляет учебное занятие в расписании.
 * <p>
 * Является закрытым (sealed) интерфейсом, что означает, что реализовывать его
 * могут только три конкретных класса: {@link Lecture}, {@link Practice} и {@link Lab}.
 * Это гарантирует, что в системе не появится неизвестных типов занятий, которые
 * не будут обработаны логикой программы.
 */
public sealed interface Lesson permits Lecture, Practice, Lab {

    /**
     * Возвращает учебную дисциплину, по которой проводится занятие.
     *
     * @return дисциплина
     */
    Discipline discipline();

    /**
     * Возвращает преподавателя, ведущего занятие.
     *
     * @return преподаватель
     */
    Teacher teacher();

    /**
     * Возвращает номер пары (время проведения занятия).
     *
     * @return номер пары
     */
    PairNumber pair();

    /**
     * Возвращает список учебных групп, участвующих в занятии.
     * Для лекции это может быть несколько групп (поток), для практики и
     * лабораторной — одна группа.
     *
     * @return список групп
     */
    List<Group> groups();

    /**
     * Возвращает строковое название типа занятия (например, "Лекция").
     *
     * @return тип занятия
     */
    String kind();
}